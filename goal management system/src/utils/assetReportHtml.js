export function buildAssetReportHtml(client) {
  const alloc = normalizeAllocation(client.assetAllocation);
  const t = allocationTotals(alloc);
  const dateStr = new Date().toLocaleDateString('en-IN', { day: '2-digit', month: 'short', year: 'numeric' });

  // One detail card per group-with-data, across all three sections, tagged
  // with its parent section for theming — flattened so pagination (2 per
  // page) doesn't need to know or care how many groups any one section has.
  const allCols = [];
  ['financial', 'physical', 'liabilities'].forEach(sectionId => {
    sectionGroupColumns(alloc, sectionId).filter(c => c.items.length > 0).forEach(col => {
      allCols.push({ col, sectionId });
    });
  });

  const detailPageCount = Math.max(0, Math.ceil(allCols.length / 2));
  const totalPages = 1 + detailPageCount + 1;

  // Auto-generated insight: equity/debt/commodity mix as a share of total
  // assets, plus the single largest holding across the whole portfolio.
  const assetMixParts = [];
  if (t.totalAssets > 0) {
    if (t.equity > 0) assetMixParts.push(`${fmtPct(t.equity, t.totalAssets)} equity`);
    if (t.debt > 0) assetMixParts.push(`${fmtPct(t.debt, t.totalAssets)} debt`);
    if (t.commodity > 0) assetMixParts.push(`${fmtPct(t.commodity, t.totalAssets)} commodity`);
  }
  const physicalShare = t.totalAssets > 0 && t.physical > 0 ? fmtPct(t.physical, t.totalAssets) : null;

  let largestHolding = null;
  allCols.forEach(({ col }) => {
    col.items.forEach(it => {
      if (!largestHolding || it.amount > largestHolding.amount) largestHolding = it;
    });
  });

  let insightText;
  if (t.totalAssets === 0) {
    insightText = 'No asset holdings have been recorded yet for this client — once allocation data is entered, this section will summarize the portfolio mix automatically.';
  } else {
    const mixSentence = assetMixParts.length > 0
      ? `Within financial holdings, the mix is currently ${assetMixParts.join(', ')}${physicalShare ? `, alongside physical assets making up ${physicalShare} of total assets` : ''}.`
      : (physicalShare ? `Physical assets make up ${physicalShare} of total assets.` : '');
    const largestSentence = largestHolding ? ` The single largest holding is <strong>${largestHolding.label}</strong> at ${fmtINR(largestHolding.amount)}.` : '';
    const debtNote = t.liabilities > 0 ? ` Outstanding liabilities of ${fmtINR(t.liabilities)} bring net worth to ${fmtINR(t.netWorth)}.` : ' This client carries no outstanding liabilities.';
    insightText = `${mixSentence}${largestSentence}${debtNote}`;
  }

  let pageNum = 1;
  let html = buildOverviewPage(client, alloc, t, dateStr, pageNum++, totalPages);

  for (let i = 0; i < allCols.length; i += 2) {
    html += buildDetailPage(allCols.slice(i, i + 2), dateStr, pageNum++, totalPages);
  }

  html += buildClosingPage(client, alloc, t, insightText, dateStr, pageNum++, totalPages);

  return html;
}
