// A table item for the page packer: `cols` = [{ label, align, width }],
// `rows` = [{ html, h }] (pre-rendered <tr>s with their estimated height).
function tableItem({ title, cols, rows, foot, emptyText }) {
  const head = `<tr style="background:#0f1f3d;">${cols.map(c => `<th style="${TH}text-align:${c.align || 'left'};${c.width ? `width:${c.width};` : ''}">${c.label}</th>`).join('')}</tr>`;
  return {
    type: 'table',
    titleH: title ? SUB_HEADING_H : 0,
    headH: TABLE_HEAD_H,
    footH: foot ? TABLE_FOOT_H : 0,
    emptyH: 40,
    rows,
    render: ({ rowsHtml, withFoot, continued }) => `
    ${title ? subHeading(`${title}${continued ? ' <span style="font-size:10px;font-weight:600;color:#94a3b8;">(continued)</span>' : ''}`) : ''}
    <div data-table-frame style="border:1px solid #e2e8f0;border-radius:12px;overflow:hidden;">
      <table style="width:100%;border-collapse:collapse;table-layout:fixed;">
        <thead>${head}</thead>
        <tbody>${rowsHtml || `<tr><td colspan="${cols.length}" style="${TD}text-align:center;color:#94a3b8;font-style:italic;padding:14px;">${emptyText || 'No data available.'}</td></tr>`}</tbody>
        ${withFoot && foot ? `<tfoot>${foot}</tfoot>` : ''}
      </table>
    </div>`,
  };
}

