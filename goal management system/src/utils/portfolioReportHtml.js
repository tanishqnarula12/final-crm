// Statement data comes from AI extraction of an uploaded PDF and the notes
// are free-typed — escape everything that lands in the HTML.
function esc(str) {
  return String(str ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

const num = (n) => (isFinite(n) ? Number(n) : 0);
const money = (n) => fmtINR(num(n));
const signedMoney = (n) => `${num(n) >= 0 ? '+' : '−'}${fmtINR(Math.abs(num(n)))}`;
const rupees = (n) => `₹${Math.round(num(n)).toLocaleString('en-IN')}`;
const pct = (n, d = 1) => `${num(n).toFixed(d)}%`;
const signedPct = (n, d = 1) => `${num(n) >= 0 ? '+' : '−'}${Math.abs(num(n)).toFixed(d)}%`;
const gainHex = (n) => (num(n) >= 0 ? '#16a34a' : '#dc2626');
const xirrHex = (n) => (num(n) >= 10 ? '#16a34a' : num(n) >= 0 ? '#475569' : '#dc2626');
const lines = (text, perLine) => Math.max(1, Math.ceil(String(text || '').length / perLine));

