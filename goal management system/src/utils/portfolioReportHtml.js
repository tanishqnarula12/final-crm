function holdingsSection(d) {
  const holdings = d.holdings || [];
  const total = holdings.reduce((s, h) => s + num(h.current), 0) || 1;
  const rows = holdings.map((h) => {
    const g = num(h.current) - num(h.invested);
    const gp = num(h.invested) ? (g / num(h.invested)) * 100 : 0;
    const al = (num(h.current) / total) * 100;
    const b = BADGE[h.badge] || BADGE.go;
    const nameLines = lines(h.name, 30);
    const catLines = lines(h.cat, 15);
    return {
      h: Math.max(16 + nameLines * 14 + (h.holder ? 13 : 0), 20 + catLines * 12),
      html: `<tr>
        <td style="${TD}">
          <div style="font-size:10px;font-weight:700;color:#0f172a;line-height:1.4;">${esc(h.name || '—')}</div>
          ${h.holder ? `<div style="font-size:8.5px;color:#94a3b8;margin-top:1px;">Holder: ${esc(h.holder)}</div>` : ''}
        </td>
        <td style="${TD}"><span style="display:inline-block;font-size:8.5px;font-weight:700;color:${b.fg};background:${b.bg};padding:2px 7px;border-radius:99px;line-height:1.4;">${esc(h.cat || '—')}</span></td>
        <td style="${TD}text-align:right;white-space:nowrap;">${money(h.invested)}</td>
        <td style="${TD}text-align:right;white-space:nowrap;font-weight:700;color:#0f172a;">${money(h.current)}</td>
        <td style="${TD}text-align:right;white-space:nowrap;font-weight:700;color:${gainHex(g)};">${signedPct(gp)}</td>
        <td style="${TD}text-align:right;white-space:nowrap;font-weight:600;color:#475569;">${pct(al)}</td>
        <td style="${TD}text-align:right;white-space:nowrap;font-weight:700;color:${xirrHex(h.xirr)};">${pct(h.xirr, 2)}</td>
      </tr>`,
    };
  });
  const invested = holdings.reduce((s, h) => s + num(h.invested), 0);
  const current = holdings.reduce((s, h) => s + num(h.current), 0);
  const gainAll = invested ? ((current - invested) / invested) * 100 : 0;
  const foot = holdings.length ? `<tr>
    <td style="${TF}" colspan="2">Total · ${holdings.length} scheme${holdings.length === 1 ? '' : 's'}</td>
    <td style="${TF}text-align:right;white-space:nowrap;">${money(invested)}</td>
    <td style="${TF}text-align:right;white-space:nowrap;">${money(current)}</td>
    <td style="${TF}text-align:right;white-space:nowrap;color:${gainHex(gainAll)};">${signedPct(gainAll)}</td>
    <td style="${TF}text-align:right;">100%</td>
    <td style="${TF}"></td>
  </tr>` : '';

  // An individual member's own SIP mandates (the All Members view has the
  // consolidated SIP tables instead).
  const sips = d.isAll ? [] : (d.sips || []);
  const sipTotal = sips.reduce((s, x) => s + num(x.amount), 0);
  const sipItem = sips.length ? tableItem({
    title: 'Active SIPs',
    cols: [{ label: 'Fund' }, { label: 'SIP date', width: '20%' }, { label: 'Monthly SIP', align: 'right', width: '20%' }],
    rows: sips.map((s, i) => ({
      h: 16 + lines(s.name, 52) * 14,
      html: `<tr>
        <td style="${TD}font-weight:600;color:#0f172a;">${dotLabel(s.name, PALETTE[i % PALETTE.length])}</td>
        <td style="${TD}">Every month · ${esc(s.date || '—')}</td>
        <td style="${TD}text-align:right;white-space:nowrap;font-weight:700;color:#0f172a;">${rupees(s.amount)}</td>
      </tr>`,
    })),
    foot: `<tr><td style="${TF}" colspan="2">Total monthly SIP</td><td style="${TF}text-align:right;white-space:nowrap;color:#16a34a;">${rupees(sipTotal)}</td></tr>`,
  }) : null;

  return {
    head: sectionHead('Scheme Holdings', `Every scheme in ${d.isAll ? 'the portfolio' : `${esc(d.memberName)}'s portfolio`}, largest holding first`),
    headH: SECTION_HEAD_H,
    items: [tableItem({
      cols: [
        { label: 'Scheme', width: '31%' },
        { label: 'Category', width: '17%' },
        { label: 'Invested', align: 'right', width: '11.5%' },
        { label: 'Current', align: 'right', width: '11.5%' },
        { label: 'Gain', align: 'right', width: '9.5%' },
        { label: 'Alloc.', align: 'right', width: '9%' },
        { label: 'XIRR', align: 'right', width: '10.5%' },
      ],
      rows,
      foot,
      emptyText: 'No holdings found in this statement.',
    }), ...(sipItem ? [sipItem] : [])],
  };
}

