// Dedicated Portfolio Review Report template — same architecture and look as
// goalReportHtml.js / assetReportHtml.js / policyReportHtml.js (see
// goalReportHtml.js for the full rationale): self-contained, inline-styled
// HTML built from data, A4 portrait pages with the shared letterhead and a
// "Page X of Y" footer, page breaks decided here rather than by the browser.
// Replaces window.print() on the live dashboard (landscape, app styling,
// charts squeezed onto the page).
//
// Unlike the goal/asset reports, the amount of content here is open-ended (a
// family statement can carry 40+ schemes, 20+ SIPs, a dozen advisory notes),
// so content is packed onto pages by estimated height: a table that runs out
// of room continues on the next page under its own header, and a section
// title never ends up alone at the bottom of a page.
