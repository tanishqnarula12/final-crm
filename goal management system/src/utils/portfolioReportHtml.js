// ── Page packer ─────────────────────────────────────────────────────────
// Each section starts on a fresh page (like the other reports' detail and
// closing pages) and flows onto as many pages as its content needs — except
// that a section joins the current page when that page is still mostly
// empty (e.g. it only holds the last row or two of the previous section's
// table), instead of leaving that page nearly blank.
const inlineHead = (sec) => `<div style="margin-top:34px;">${sec.head(false)}</div>`;
const INLINE_HEAD_H = 96;

// Room the first item of a section needs, so a section never starts with
// its heading alone at the bottom of a page.
function firstNeed(item) {
  if (!item) return 0;
  if (item.type === 'block') return item.h;
  const r = item.rows;
  if (!r.length) return item.titleH + item.headH + item.emptyH;
  return item.titleH + item.headH + r[0].h + (r[1] ? r[1].h : item.footH);
}

function paginate(sections, budget) {
  const pages = [];
  let page = null;
  let used = 0;
  sections.forEach((sec) => {
    const open = (continued) => {
      page = { head: sec.head(continued), parts: [] };
      used = continued ? (sec.headContH ?? sec.headH) : sec.headH;
      pages.push(page);
    };
    const fits = (h) => used + h <= budget;
    const inlineH = sec.inlineHeadH ?? INLINE_HEAD_H;
    if (page && used < budget / 2 && fits(inlineH + firstNeed(sec.items[0]))) {
      page.parts.push(inlineHead(sec));
      used += inlineH;
    } else {
      open(false);
    }

    sec.items.forEach((item) => {
      if (item.type === 'block') {
        if (!fits(item.h + item.keepWithNext) && page.parts.length) open(true);
        page.parts.push(item.html);
        used += item.h;
        return;
      }
      // table
      const { rows } = item;
      let i = 0;
      let first = true;
      do {
        const lead = item.titleH + item.headH;
        // A table only starts on this page if at least two of its rows (or
        // all of them, if fewer) fit under its header.
        const minRows = Math.min(2, rows.length - i);
        let minNeed = lead + (rows.length ? 0 : item.emptyH) + (rows.length - i <= minRows ? item.footH : 0);
        for (let k = 0; k < minRows; k++) minNeed += rows[i + k].h;
        if (!fits(minNeed) && page.parts.length) open(true);
        let h = lead;
        const chunk = [];
        while (i < rows.length) {
          const add = rows[i].h + (i === rows.length - 1 ? item.footH : 0);
          if (chunk.length && !fits(h + add)) break;
          chunk.push(rows[i].html);
          h += rows[i].h;
          i++;
        }
        // …and never carries a single last row over to the next page alone.
        if (i === rows.length - 1 && chunk.length >= 3) {
          chunk.pop();
          i--;
          h -= rows[i].h;
        }
        const done = i >= rows.length;
        if (done) h += rows.length ? item.footH : item.emptyH;
        page.parts.push(item.render({ rowsHtml: chunk.join(''), withFoot: done, continued: !first }));
        used += h;
        first = false;
        if (!done) open(true);
      } while (i < rows.length);
    });
  });
  return pages;
}

function sectionHead(title, caption) {
  return (continued) => `
    <div style="font-family:'Playfair Display',serif;font-size:22px;font-weight:700;color:#0f172a;letter-spacing:-0.4px;">${title}${continued ? ' <span style="font-family:\'DM Sans\',sans-serif;font-size:11px;font-weight:600;color:#94a3b8;letter-spacing:0;">(continued)</span>' : ''}</div>
    <div style="font-size:10.5px;color:#64748b;margin-top:4px;margin-bottom:6px;">${caption}</div>`;
}
