// Workbook entry point
// ---------------------------------------------------------------------------

/**
 * Reads every worksheet in the workbook and returns one descriptor per sheet.
 *
 * Sheet count and names are whatever the file contains — nothing is hard-coded
 * and nothing is skipped, so a workbook that gains or loses categories next
 * month imports correctly with no code change.
 *
 * `raw: false` is deliberate: it yields the FORMATTED display strings Excel
 * shows ("19.59%"), which is both what the raw view must reproduce and what
 * parseNumber can read back correctly. With `raw: true` a percent-formatted
 * cell arrives as 0.1959 and would render as a wrong-looking number.
 */
export function parseWorkbook(arrayBuffer, fileName, now = new Date()) {
  const wb = XLSX.read(arrayBuffer, { type: 'array', cellDates: true });
  const sheets = [];

  wb.SheetNames.forEach((name, sheetIndex) => {
    const ws = wb.Sheets[name];
    if (!ws) return;

    // `blankrows: true` keeps the array index of every row equal to its real
    // position in the sheet, so `headerRowIndex` and the "row N" note in
    // avgMedianSource line up with the row numbers the user sees in Excel.
    // Blank rows are dropped later, when building the displayable rawRows.
    const aoa = XLSX.utils.sheet_to_json(ws, {
      header: 1,
      defval: '',
      blankrows: true,
      raw: false,
    }).map((row) => (Array.isArray(row) ? row.map((c) => (c == null ? '' : String(c))) : []));

    // A sheet with nothing on it is still reported (so the user can see it was
    // present in the file) but carries no rows to analyse.
    if (!aoa.some((r) => r.some((c) => txt(c)))) {
      sheets.push({
        name, sheetIndex, aoa: [], headerRowIndex: 0, headers: [], rawRows: [],
        schemeCol: null, medianCol: null, avgMedian: null, avgMedianSource: null,
        empty: true,
      });
      return;
    }

    const headerRowIndex = detectHeaderRow(aoa);
    const width = aoa.reduce((w, r) => Math.max(w, r.length), 0);
    const headers = normalizeHeaders(aoa[headerRowIndex], width);

    // Every row below the header, padded to a uniform width so the raw table
    // renders as a clean grid. Summary/footer rows are kept here (raw must be
    // verbatim) and excluded from analysis further down.
    const allBelow = aoa.slice(headerRowIndex + 1)
      .map((r) => Array.from({ length: width }, (_, i) => (r?.[i] == null ? '' : String(r[i]))))
      .filter((r) => r.some((c) => txt(c)));

    const schemeCol = detectSchemeCol(headers, allBelow);
    const medianCol = detectMedianCol(headers);
    const avg = detectAvgMedian(aoa, headers, headerRowIndex);

    sheets.push({
      name,
      sheetIndex,
      aoa,
      headerRowIndex,
      headers,
      rawRows: allBelow,
      schemeCol,
      medianCol,
      avgMedian: avg.value,
      avgMedianSource: avg.source,
      empty: false,
    });
  });

  const month = detectReportingMonth(fileName, sheets, now);
  return { sheets, detectedMonth: month.key, monthSource: month.source };
}

/**
 * Rows that should be ANALYSED, as opposed to merely displayed. Drops the
 * category's own summary/footer lines ("Average Median", "Total", …), which
 * are not schemes — they stay visible in the raw view regardless.
 */
export function analysisRows(sheet) {
  if (sheet.schemeCol == null) return [];
  return (sheet.rawRows || []).filter((r) => {
    const label = txt(r[sheet.schemeCol]);
    return label && !SUMMARY_ROW_RE.test(label);
  });
}

/**
 * Turns a parsed + reviewed sheet into the payload the API stores: the raw
 * worksheet verbatim, plus the derived analysis rows alongside it.
 */
export function buildCategoryPayload(sheet, reportingMonth) {
  const rows = analysisRows(sheet);
  const schemes = screenCategory({
    rawRows: rows,
    schemeCol: sheet.schemeCol,
    medianCol: sheet.medianCol,
    avgMedian: sheet.avgMedian,
  });
  return {
    name: sheet.name,
    sheetIndex: sheet.sheetIndex,
    avgMedian: sheet.avgMedian,
    avgMedianSource: sheet.avgMedianSource,
    rawHeaders: sheet.headers,
    rawRows: sheet.rawRows,
    headerRowIndex: sheet.headerRowIndex,
    schemeCol: sheet.schemeCol,
    medianCol: sheet.medianCol,
    schemes: schemes.map((s) => ({ ...s, reportingMonth, categoryName: sheet.name })),
  };
}

// Display helper — a percentage that keeps two decimals and never prints
// "NaN%" / "null%" for a genuinely missing value.
export const pct = (v, digits = 2) =>
  v === null || v === undefined || !Number.isFinite(Number(v))
    ? '—'
    : `${Number(v).toFixed(digits)}%`;

export const signedPct = (v, digits = 2) =>
  v === null || v === undefined || !Number.isFinite(Number(v))
    ? '—'
    : `${Number(v) > 0 ? '+' : ''}${Number(v).toFixed(digits)}%`;
